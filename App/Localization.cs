    public static readonly (string Code, string Name)[] Languages =
    {
        ("en", "English"),
        ("zh-CN", "简体中文"),
        ("zh-TW", "繁體中文"),
        ("ja", "日本語"),
        ("ko", "한국어"),
        ("de", "Deutsch"),
        ("fr", "Français"),
        ("es", "Español")
    };

    public static string Code { get; private set; } = "en";

    public static event Action? Changed;

    public static bool IsSupported(string? code) =>
        !string.IsNullOrWhiteSpace(code) && Data.ContainsKey(code);

    public static void SetLanguage(string? code)
    {
        if (!IsSupported(code)) return;
        if (string.Equals(Code, code, StringComparison.OrdinalIgnoreCase)) return;
        Code = Data.Keys.First(k => string.Equals(k, code, StringComparison.OrdinalIgnoreCase));
        Changed?.Invoke();
    }

    public static string T(string key)
    {
        if (Data.TryGetValue(Code, out var dict) && dict.TryGetValue(key, out var value))
            return value;
        if (Data.TryGetValue("en", out var en) && en.TryGetValue(key, out var fallback))
            return fallback;
        return key;
    }

    public static string Format(string key, params object[] args)
    {
        try { return string.Format(T(key), args); }
        catch { return T(key); }
    }

    public static string DetectLanguage()
    {
        var culture = CultureInfo.CurrentUICulture;
        string name = culture.Name;
        if (name.StartsWith("zh", StringComparison.OrdinalIgnoreCase))
        {
            if (name.Contains("Hant", StringComparison.OrdinalIgnoreCase) ||
                name.Contains("TW", StringComparison.OrdinalIgnoreCase) ||
                name.Contains("HK", StringComparison.OrdinalIgnoreCase) ||
                name.Contains("MO", StringComparison.OrdinalIgnoreCase))
                return "zh-TW";
            return "zh-CN";
        }

        string two = culture.TwoLetterISOLanguageName;
        return two switch
        {
            "ja" => "ja",
            "ko" => "ko",
            "de" => "de",
            "fr" => "fr",
            "es" => "es",
            _ => "en"
        };
    }

    public static string GetName(string code) => Languages.FirstOrDefault(l => l.Code == code).Name ?? "English";
